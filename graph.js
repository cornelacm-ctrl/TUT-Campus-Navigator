const autoEdgeSettings = {
  closeJunctionMaxDistanceMeters: 42,
  junctionNearestMaxDistanceMeters: 65,
  junctionNearestCount: 2,
  entranceMaxDistanceMeters: 45,
  componentBridgeMaxDistanceMeters: 90,
  shortcutMaxDistanceMeters: 85,
  shortcutMinRouteRatio: 2.2
};

function distance(a, b) {
  const earthRadiusMeters = 6371000;
  const lat1 = a.lat * Math.PI / 180;
  const lat2 = b.lat * Math.PI / 180;
  const deltaLat = (b.lat - a.lat) * Math.PI / 180;
  const deltaLng = (b.lng - a.lng) * Math.PI / 180;

  const haversine =
    Math.sin(deltaLat / 2) * Math.sin(deltaLat / 2) +
    Math.cos(lat1) * Math.cos(lat2) *
    Math.sin(deltaLng / 2) * Math.sin(deltaLng / 2);

  return earthRadiusMeters * 2 * Math.atan2(Math.sqrt(haversine), Math.sqrt(1 - haversine));
}

function normalizeBuildingKey(value) {
  return String(value || "").toLowerCase().replace(/[^a-z0-9]/g, "");
}

function getBuildingKey(value) {
  const match = String(value || "").match(/building\s*\d+/i);
  return match ? normalizeBuildingKey(match[0]) : normalizeBuildingKey(value);
}

function getNodeBuildingKey(nodeId) {
  const match = String(nodeId || "").match(/building\s*\d+/i);
  return match ? normalizeBuildingKey(match[0]) : null;
}

function addGraphEdge(edges, nodes, from, to) {
  if (!nodes[from] || !nodes[to] || from === to) return;

  if (!edges[from]) edges[from] = [];
  if (!edges[to]) edges[to] = [];

  if (!edges[from].includes(to)) edges[from].push(to);
  if (!edges[to].includes(from)) edges[to].push(from);
}

function hasGraphEdge(edges, from, to) {
  return (edges[from] || []).includes(to);
}

function isNodeType(node, type) {
  return String(node.type).toLowerCase() === type;
}

function getNearbyNodeIds(nodes, fromId, predicate, maxDistanceMeters) {
  const fromNode = nodes[fromId];

  return Object.keys(nodes)
    .filter(id => id !== fromId && predicate(id, nodes[id]))
    .map(id => ({
      id,
      meters: distance(fromNode, nodes[id])
    }))
    .filter(candidate => candidate.meters <= maxDistanceMeters)
    .sort((a, b) => a.meters - b.meters)
    .map(candidate => candidate.id);
}

function connectNearbyJunctions(edges, nodes) {
  const junctionIds = Object.keys(nodes).filter(id => isNodeType(nodes[id], "junction"));

  for (let i = 0; i < junctionIds.length; i++) {
    for (let j = i + 1; j < junctionIds.length; j++) {
      const from = junctionIds[i];
      const to = junctionIds[j];

      if (distance(nodes[from], nodes[to]) <= autoEdgeSettings.closeJunctionMaxDistanceMeters) {
        addGraphEdge(edges, nodes, from, to);
      }
    }
  }

  junctionIds.forEach(junctionId => {
    getNearbyNodeIds(
      nodes,
      junctionId,
      (id, node) => isNodeType(node, "junction"),
      autoEdgeSettings.junctionNearestMaxDistanceMeters
    )
      .slice(0, autoEdgeSettings.junctionNearestCount)
      .forEach(nearestJunctionId => {
        addGraphEdge(edges, nodes, junctionId, nearestJunctionId);
      });
  });
}

function connectEntrances(edges, nodes) {
  const entranceIds = Object.keys(nodes).filter(id => isNodeType(nodes[id], "entrance"));

  entranceIds.forEach(entranceId => {
    const nearbyJunctions = getNearbyNodeIds(
      nodes,
      entranceId,
      (id, node) => isNodeType(node, "junction"),
      autoEdgeSettings.entranceMaxDistanceMeters
    );

    nearbyJunctions.forEach(junctionId => {
      addGraphEdge(edges, nodes, entranceId, junctionId);
    });

    if (nearbyJunctions.length === 0) {
      const nearestJunctionId = Object.keys(nodes)
        .filter(id => isNodeType(nodes[id], "junction"))
        .sort((a, b) => distance(nodes[entranceId], nodes[a]) - distance(nodes[entranceId], nodes[b]))[0];

      addGraphEdge(edges, nodes, entranceId, nearestJunctionId);
    }
  });
}

function getConnectedComponents(edges, nodes) {
  const unvisited = new Set(Object.keys(nodes));
  const components = [];

  while (unvisited.size > 0) {
    const startId = unvisited.values().next().value;
    const stack = [startId];
    const component = [];

    unvisited.delete(startId);

    while (stack.length > 0) {
      const currentId = stack.pop();
      component.push(currentId);

      (edges[currentId] || []).forEach(nextId => {
        if (!unvisited.has(nextId)) return;

        unvisited.delete(nextId);
        stack.push(nextId);
      });
    }

    components.push(component);
  }

  return components;
}

function findClosestComponentBridge(components, nodes) {
  let closestBridge = null;

  for (let i = 0; i < components.length; i++) {
    for (let j = i + 1; j < components.length; j++) {
      const fromCandidates = components[i].filter(id => isNodeType(nodes[id], "junction"));
      const toCandidates = components[j].filter(id => isNodeType(nodes[id], "junction"));

      if (fromCandidates.length === 0 || toCandidates.length === 0) continue;

      fromCandidates.forEach(fromId => {
        toCandidates.forEach(toId => {
          const meters = distance(nodes[fromId], nodes[toId]);

          if (!closestBridge || meters < closestBridge.meters) {
            closestBridge = { fromId, toId, meters };
          }
        });
      });
    }
  }

  return closestBridge;
}

function connectDisconnectedComponents(edges, nodes) {
  let components = getConnectedComponents(edges, nodes);

  while (components.length > 1) {
    const bridge = findClosestComponentBridge(components, nodes);

    if (!bridge || bridge.meters > autoEdgeSettings.componentBridgeMaxDistanceMeters) break;

    addGraphEdge(edges, nodes, bridge.fromId, bridge.toId);
    components = getConnectedComponents(edges, nodes);
  }
}

function getShortestGraphDistance(edges, nodes, start, end) {
  if (!nodes[start] || !nodes[end]) return Infinity;

  const distances = {};
  const unvisited = new Set(Object.keys(nodes));

  Object.keys(nodes).forEach(id => {
    distances[id] = Infinity;
  });

  distances[start] = 0;

  while (unvisited.size > 0) {
    let current = null;

    unvisited.forEach(id => {
      if (current === null || distances[id] < distances[current]) {
        current = id;
      }
    });

    if (current === null || distances[current] === Infinity) break;
    if (current === end) return distances[current];

    unvisited.delete(current);

    (edges[current] || []).forEach(next => {
      if (!unvisited.has(next)) return;

      const nextDistance = distances[current] + distance(nodes[current], nodes[next]);

      if (nextDistance < distances[next]) {
        distances[next] = nextDistance;
      }
    });
  }

  return distances[end];
}

function connectUsefulShortcuts(edges, nodes) {
  const junctionIds = Object.keys(nodes).filter(id => isNodeType(nodes[id], "junction"));

  while (true) {
    let bestShortcut = null;

    for (let i = 0; i < junctionIds.length; i++) {
      for (let j = i + 1; j < junctionIds.length; j++) {
        const from = junctionIds[i];
        const to = junctionIds[j];

        if (hasGraphEdge(edges, from, to)) continue;

        const directDistance = distance(nodes[from], nodes[to]);

        if (directDistance > autoEdgeSettings.shortcutMaxDistanceMeters) continue;

        const currentDistance = getShortestGraphDistance(edges, nodes, from, to);

        if (!Number.isFinite(currentDistance)) continue;
        if (currentDistance < directDistance * autoEdgeSettings.shortcutMinRouteRatio) continue;

        const savedDistance = currentDistance - directDistance;

        if (!bestShortcut || savedDistance > bestShortcut.savedDistance) {
          bestShortcut = { from, to, savedDistance };
        }
      }
    }

    if (!bestShortcut) break;

    addGraphEdge(edges, nodes, bestShortcut.from, bestShortcut.to);
  }
}

function replaceObjectContents(target, source) {
  Object.keys(target).forEach(key => {
    delete target[key];
  });

  Object.keys(source).forEach(key => {
    target[key] = source[key];
  });
}

function buildGraphEdges(nodes, manualEdges) {
  const edges = {};

  Object.keys(nodes).forEach(id => {
    edges[id] = [];
  });

  Object.keys(manualEdges).forEach(from => {
    manualEdges[from].forEach(to => {
      addGraphEdge(edges, nodes, from, to);
    });
  });

  connectNearbyJunctions(edges, nodes);
  connectEntrances(edges, nodes);
  connectDisconnectedComponents(edges, nodes);
  connectUsefulShortcuts(edges, nodes);

  return edges;
}

